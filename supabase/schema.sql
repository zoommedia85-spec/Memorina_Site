create table public.settings (
  id int primary key default 1 check (id = 1),
  whatsapp_number text not null check (whatsapp_number ~ '^[0-9]{8,15}$'),
  instagram_url text not null default '' check (instagram_url = '' or instagram_url ~ '^https://[^[:space:]<>"'']+$'),
  reviews_link_url text not null default '' check (reviews_link_url = '' or reviews_link_url ~ '^https://[^[:space:]<>"'']+$'),
  currency text not null default 'ج.م' check (char_length(currency) between 1 and 10),
  updated_at timestamptz not null default now()
);

create table public.app_secrets (
  key text primary key,
  value text not null
);
insert into public.app_secrets (key, value) values ('ip_salt', gen_random_uuid()::text);

create table public.admins (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create table public.collections (
  id text primary key check (id ~ '^[a-z0-9_-]{1,40}$'),
  name text not null check (char_length(name) between 1 and 80),
  description text not null default '' check (char_length(description) <= 400),
  cover_url text not null default '' check (cover_url = '' or cover_url ~ '^https://[^/]+/storage/v1/object/public/media/[A-Za-z0-9_./-]+$'),
  icon text not null default 'gift' check (icon in ('frame', 'medal', 'notebook', 'glasses', 'cane', 'gift')),
  hide_prices boolean not null default false,
  is_active boolean not null default true,
  sort_order int not null default 0,
  created_at timestamptz not null default now()
);

create table public.products (
  id text primary key check (id ~ '^[a-z0-9_-]{1,40}$'),
  collection_id text not null references public.collections (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 120),
  description text not null default '' check (char_length(description) <= 600),
  images text[] not null default '{}',
  icon text not null default 'gift' check (icon in ('frame', 'medal', 'notebook', 'glasses', 'cane', 'gift')),
  price numeric(10, 2) check (price is null or (price >= 0 and price <= 1000000)),
  sizes jsonb,
  quantity_tiers jsonb,
  hide_price boolean not null default false,
  ribbon_text text not null default '' check (char_length(ribbon_text) <= 30),
  ribbon_color text not null default 'coral' check (ribbon_color in ('coral', 'sage', 'gold', 'dark')),
  is_active boolean not null default true,
  sort_order int not null default 0,
  created_at timestamptz not null default now(),
  constraint products_one_pricing_mode check (
    (case when price is not null then 1 else 0 end)
    + (case when sizes is not null then 1 else 0 end)
    + (case when quantity_tiers is not null then 1 else 0 end) = 1
  )
);
create index products_collection_idx on public.products (collection_id);

create table public.shipping_rates (
  id bigint generated by default as identity primary key,
  name text not null unique check (char_length(name) between 1 and 60),
  price numeric(10, 2) not null check (price >= 0 and price <= 100000),
  sort_order int not null default 0,
  is_active boolean not null default true
);

create table public.review_images (
  id bigint generated by default as identity primary key,
  url text not null check (url ~ '^https://[^/]+/storage/v1/object/public/media/[A-Za-z0-9_./-]+$'),
  sort_order int not null default 0
);

create table public.orders (
  id bigint generated always as identity (start with 1001) primary key,
  created_at timestamptz not null default now(),
  customer_name text not null,
  phone text not null,
  governorate text not null,
  address text not null,
  items jsonb not null,
  subtotal numeric(12, 2) not null,
  shipping numeric(10, 2) not null,
  total numeric(12, 2) not null,
  has_unpriced boolean not null default false,
  status text not null default 'new' check (status in ('new', 'confirmed', 'in_progress', 'shipped', 'delivered', 'cancelled')),
  note text not null default '' check (char_length(note) <= 1000),
  ip_hash text not null default ''
);
create index orders_created_idx on public.orders (created_at desc);
create index orders_ip_idx on public.orders (ip_hash, created_at);
create index orders_phone_idx on public.orders (phone, created_at);

