create or replace function public.get_catalog()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'settings', (
      select jsonb_build_object(
        'whatsapp', s.whatsapp_number,
        'instagram', s.instagram_url,
        'reviewsLink', s.reviews_link_url,
        'currency', s.currency
      ) from public.settings s where s.id = 1
    ),
    'collections', coalesce((
      select jsonb_agg(
        jsonb_build_object('id', c.id, 'name', c.name, 'desc', c.description, 'cover', c.cover_url, 'icon', c.icon)
        order by c.sort_order, c.created_at
      ) from public.collections c where c.is_active
    ), '[]'::jsonb),
    'products', coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'id', p.id,
          'collectionId', p.collection_id,
          'name', p.name,
          'desc', p.description,
          'images', to_jsonb(p.images),
          'icon', p.icon,
          'ribbon', case when p.ribbon_text <> ''
                         then jsonb_build_object('text', p.ribbon_text, 'color', p.ribbon_color)
                         else null end,
          'hidePrice', (p.hide_price or c.hide_prices),
          'price', case when p.hide_price or c.hide_prices then null else p.price end,
          'sizes', case
            when p.sizes is null then null
            when p.hide_price or c.hide_prices then (
              select jsonb_agg(jsonb_build_object('label', s.value ->> 'label') order by s.n)
              from jsonb_array_elements(p.sizes) with ordinality as s(value, n))
            else p.sizes end,
          'tiers', case
            when p.quantity_tiers is null then null
            when p.hide_price or c.hide_prices then (
              select jsonb_agg(jsonb_build_object('min', t.value -> 'min', 'max', t.value -> 'max') order by t.n)
              from jsonb_array_elements(p.quantity_tiers) with ordinality as t(value, n))
            else p.quantity_tiers end
        )
        order by p.sort_order, p.created_at
      )
      from public.products p
      join public.collections c on c.id = p.collection_id
      where p.is_active and c.is_active
    ), '[]'::jsonb),
    'shipping', coalesce((
      select jsonb_agg(jsonb_build_object('name', r.name, 'price', r.price) order by r.sort_order, r.id)
      from public.shipping_rates r where r.is_active
    ), '[]'::jsonb),
    'reviews', coalesce((
      select jsonb_agg(v.url order by v.sort_order, v.id) from public.review_images v
    ), '[]'::jsonb)
  );
$$;

create or replace function public.create_order(payload jsonb)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_name text;
  v_phone text;
  v_gov text;
  v_addr text;
  v_items jsonb;
  v_item jsonb;
  v_id text;
  v_size text;
  v_qty int;
  v_prod public.products;
  v_hidden boolean;
  v_unit numeric;
  v_line_total numeric;
  v_lines jsonb := '[]'::jsonb;
  v_subtotal numeric := 0;
  v_has_priced boolean := false;
  v_has_unpriced boolean := false;
  v_ship numeric;
  v_total numeric;
  v_headers jsonb;
  v_ip text;
  v_ip_hash text;
  v_salt text;
  v_cnt int;
  v_order_id bigint;
  v_currency text;
  v_msg text;
  r record;
begin
  if payload is null then
    raise exception 'bad_request';
  end if;
  if jsonb_typeof(payload) <> 'object' then
    raise exception 'bad_request';
  end if;

  -- حقل مخفي: البوتات بتملاه والمستخدم العادي لا
  if coalesce(payload ->> 'website', '') <> '' then
    return jsonb_build_object('ok', true, 'orderNo', 0, 'message', '');
  end if;

  v_name := btrim(regexp_replace(regexp_replace(coalesce(payload ->> 'name', ''), '[[:cntrl:]]', ' ', 'g'), '\s+', ' ', 'g'));
  if char_length(v_name) not between 2 and 100 then
    raise exception 'invalid_name';
  end if;

  v_phone := translate(coalesce(payload ->> 'phone', ''), '٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹', '01234567890123456789');
  v_phone := regexp_replace(v_phone, '[[:space:]().-]', '', 'g');
  v_phone := regexp_replace(v_phone, '^\+', '');
  if v_phone !~ '^[0-9]{8,15}$' then
    raise exception 'invalid_phone';
  end if;

  v_addr := btrim(regexp_replace(regexp_replace(coalesce(payload ->> 'address', ''), '[[:cntrl:]]', ' ', 'g'), '\s+', ' ', 'g'));
  if char_length(v_addr) not between 5 and 400 then
    raise exception 'invalid_address';
  end if;

  v_gov := btrim(coalesce(payload ->> 'governorate', ''));
  select s.price into v_ship
  from public.shipping_rates s
  where s.name = v_gov and s.is_active;
  if not found then
    raise exception 'invalid_governorate';
  end if;

  v_items := payload -> 'items';
  if v_items is null then
    raise exception 'invalid_items';
  end if;
  if jsonb_typeof(v_items) <> 'array' then
    raise exception 'invalid_items';
  end if;
  if jsonb_array_length(v_items) not between 1 and 40 then
    raise exception 'invalid_items';
  end if;

  select s.currency into v_currency from public.settings s where s.id = 1;
  v_currency := coalesce(v_currency, '');

  for v_item in select value from jsonb_array_elements(v_items) loop
    if jsonb_typeof(v_item) <> 'object' then
      raise exception 'invalid_items';
    end if;

    v_id := v_item ->> 'id';
    if v_id is null or v_id !~ '^[a-z0-9_-]{1,40}$' then
      raise exception 'invalid_product';
    end if;
    if coalesce(v_item ->> 'qty', '') !~ '^[0-9]{1,4}$' then
      raise exception 'invalid_quantity';
    end if;
    v_qty := (v_item ->> 'qty')::int;
    if v_qty < 1 or v_qty > 1000 then
      raise exception 'invalid_quantity';
    end if;
    v_size := nullif(btrim(coalesce(v_item ->> 'size', '')), '');

    select p.* into v_prod
    from public.products p
    join public.collections c on c.id = p.collection_id
    where p.id = v_id and p.is_active and c.is_active;
    if not found then
      raise exception 'invalid_product';
    end if;

    select c.hide_prices into v_hidden from public.collections c where c.id = v_prod.collection_id;
    v_hidden := coalesce(v_hidden, false) or v_prod.hide_price;

    v_unit := null;
    if v_prod.quantity_tiers is not null then
      select min((t.value ->> 'rate')::numeric) into v_unit
      from jsonb_array_elements(v_prod.quantity_tiers) as t
      where v_qty >= (t.value ->> 'min')::int
        and ((t.value ->> 'max') is null or v_qty <= (t.value ->> 'max')::int);
      if v_unit is null then
        raise exception 'invalid_quantity';
      end if;
      v_size := null;
    elsif v_prod.sizes is not null then
      if v_size is null then
        raise exception 'invalid_size';
      end if;
      select (s.value ->> 'price')::numeric into v_unit
      from jsonb_array_elements(v_prod.sizes) as s
      where (s.value ->> 'label') = v_size
      limit 1;
      if v_unit is null then
        raise exception 'invalid_size';
      end if;
    else
      v_unit := v_prod.price;
      v_size := null;
    end if;

    if v_hidden then
      v_has_unpriced := true;
      v_lines := v_lines || jsonb_build_array(jsonb_build_object(
        'id', v_prod.id, 'name', v_prod.name, 'size', v_size, 'qty', v_qty, 'unit', null, 'total', null));
    else
      v_has_priced := true;
      v_line_total := v_unit * v_qty;
      v_subtotal := v_subtotal + v_line_total;
      v_lines := v_lines || jsonb_build_array(jsonb_build_object(
        'id', v_prod.id, 'name', v_prod.name, 'size', v_size, 'qty', v_qty, 'unit', v_unit, 'total', v_line_total));
    end if;
  end loop;

  v_total := v_subtotal + v_ship;

  -- لو السعر اتغير من وقت ما العميل شافه، نرجّعله يراجع السلة
  if coalesce(payload ->> 'expectedTotal', '') ~ '^[0-9]+(\.[0-9]{1,2})?$' then
    if abs((payload ->> 'expectedTotal')::numeric - v_total) > 0.009 then
      raise exception 'price_changed';
    end if;
  end if;

  -- الحد من الطلبات المتكررة
  v_headers := coalesce(nullif(current_setting('request.headers', true), '')::jsonb, '{}'::jsonb);
  v_ip := coalesce(
    nullif(v_headers ->> 'cf-connecting-ip', ''),
    nullif(v_headers ->> 'x-real-ip', ''),
    nullif(btrim(regexp_replace(coalesce(v_headers ->> 'x-forwarded-for', ''), '^.*,', '')), ''),
    'unknown'
  );
  select a.value into v_salt from public.app_secrets a where a.key = 'ip_salt';
  v_ip_hash := encode(sha256(convert_to(v_ip || coalesce(v_salt, ''), 'UTF8')), 'hex');

  if v_ip <> 'unknown' then
    select count(*) into v_cnt from public.orders o
    where o.ip_hash = v_ip_hash and o.created_at > now() - interval '10 minutes';
    if v_cnt >= 5 then
      raise exception 'rate_limited';
    end if;
    select count(*) into v_cnt from public.orders o
    where o.ip_hash = v_ip_hash and o.created_at > now() - interval '1 day';
    if v_cnt >= 30 then
      raise exception 'rate_limited';
    end if;
  end if;
  select count(*) into v_cnt from public.orders o
  where o.phone = v_phone and o.created_at > now() - interval '1 hour';
  if v_cnt >= 5 then
    raise exception 'rate_limited';
  end if;
  select count(*) into v_cnt from public.orders o
  where o.created_at > now() - interval '10 minutes';
  if v_cnt >= 150 then
    raise exception 'rate_limited';
  end if;

  insert into public.orders (customer_name, phone, governorate, address, items, subtotal, shipping, total, has_unpriced, ip_hash)
  values (v_name, v_phone, v_gov, v_addr, v_lines, v_subtotal, v_ship, v_total, v_has_unpriced, v_ip_hash)
  returning id into v_order_id;

  v_msg := 'أهلاً Memorina، عايزين نطلب الآتي (طلب رقم #' || v_order_id::text || '):' || E'\n';
  for r in select value from jsonb_array_elements(v_lines) loop
    v_msg := v_msg || '- ' || (r.value ->> 'name');
    if (r.value ->> 'size') is not null then
      v_msg := v_msg || ' (' || (r.value ->> 'size') || ')';
    end if;
    v_msg := v_msg || ' × ' || (r.value ->> 'qty');
    if (r.value ->> 'total') is not null then
      v_msg := v_msg || ' = ' || trim_scale((r.value ->> 'total')::numeric)::text || ' ' || v_currency;
    end if;
    v_msg := v_msg || E'\n';
  end loop;

  v_msg := v_msg || E'\n';
  if v_has_priced then
    v_msg := v_msg || 'سعر المنتجات: ' || trim_scale(v_subtotal)::text || ' ' || v_currency || E'\n';
  end if;
  v_msg := v_msg || 'الشحن (' || v_gov || '): ' || trim_scale(v_ship)::text || ' ' || v_currency || E'\n';
  if v_has_priced then
    v_msg := v_msg || 'الإجمالي شامل الشحن: ' || trim_scale(v_total)::text || ' ' || v_currency;
    if v_has_unpriced then
      v_msg := v_msg || ' (من غير المنتجات اللي سعرها هيتأكد معاكم)';
    end if;
    v_msg := v_msg || E'\n';
  else
    v_msg := v_msg || 'سعر المنتجات هيتأكد معاكم من التيم.' || E'\n';
  end if;
  v_msg := v_msg || E'\n'
    || 'الاسم: ' || v_name || E'\n'
    || 'رقم التليفون: ' || v_phone || E'\n'
    || 'المحافظة: ' || v_gov || E'\n'
    || 'العنوان: ' || v_addr;

  return jsonb_build_object(
    'ok', true,
    'orderNo', v_order_id,
    'subtotal', v_subtotal,
    'shipping', v_ship,
    'total', v_total,
    'hasUnpriced', v_has_unpriced,
    'message', v_msg
  );
end;
$$;

