create or replace function public.validate_product()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  e jsonb;
  img text;
begin
  if new.sizes is not null and jsonb_typeof(new.sizes) = 'null' then
    new.sizes := null;
  end if;
  if new.quantity_tiers is not null and jsonb_typeof(new.quantity_tiers) = 'null' then
    new.quantity_tiers := null;
  end if;

  if cardinality(new.images) > 20 then
    raise exception 'too many images';
  end if;
  foreach img in array new.images loop
    if img !~ '^https://[^/]+/storage/v1/object/public/media/[A-Za-z0-9_./-]+$' then
      raise exception 'invalid image url';
    end if;
  end loop;

  if new.sizes is not null then
    if jsonb_typeof(new.sizes) <> 'array' then
      raise exception 'invalid sizes';
    end if;
    if jsonb_array_length(new.sizes) not between 1 and 12 then
      raise exception 'invalid sizes count';
    end if;
    for e in select value from jsonb_array_elements(new.sizes) loop
      if coalesce(jsonb_typeof(e), '') <> 'object' then
        raise exception 'invalid size entry';
      end if;
      if coalesce(jsonb_typeof(e -> 'label'), '') <> 'string' then
        raise exception 'invalid size label';
      end if;
      if char_length(e ->> 'label') not between 1 and 30 then
        raise exception 'invalid size label length';
      end if;
      if coalesce(jsonb_typeof(e -> 'price'), '') <> 'number' then
        raise exception 'invalid size price';
      end if;
      if (e ->> 'price')::numeric not between 0 and 1000000 then
        raise exception 'invalid size price range';
      end if;
    end loop;
  end if;

  if new.quantity_tiers is not null then
    if jsonb_typeof(new.quantity_tiers) <> 'array' then
      raise exception 'invalid tiers';
    end if;
    if jsonb_array_length(new.quantity_tiers) not between 1 and 10 then
      raise exception 'invalid tiers count';
    end if;
    for e in select value from jsonb_array_elements(new.quantity_tiers) loop
      if coalesce(jsonb_typeof(e), '') <> 'object' then
        raise exception 'invalid tier entry';
      end if;
      if coalesce(jsonb_typeof(e -> 'min'), '') <> 'number' then
        raise exception 'invalid tier min';
      end if;
      if (e ->> 'min')::numeric < 1 or (e ->> 'min')::numeric <> trunc((e ->> 'min')::numeric) then
        raise exception 'invalid tier min value';
      end if;
      if coalesce(jsonb_typeof(e -> 'max'), 'null') not in ('null', 'number') then
        raise exception 'invalid tier max';
      end if;
      if jsonb_typeof(e -> 'max') = 'number' then
        if (e ->> 'max')::numeric < (e ->> 'min')::numeric or (e ->> 'max')::numeric <> trunc((e ->> 'max')::numeric) then
          raise exception 'invalid tier max value';
        end if;
      end if;
      if coalesce(jsonb_typeof(e -> 'rate'), '') <> 'number' then
        raise exception 'invalid tier rate';
      end if;
      if (e ->> 'rate')::numeric not between 0 and 1000000 then
        raise exception 'invalid tier rate range';
      end if;
    end loop;
  end if;

  return new;
end;
$$;

create trigger products_validate
  before insert or update on public.products
  for each row execute function public.validate_product();

